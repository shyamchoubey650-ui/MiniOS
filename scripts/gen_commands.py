#!/usr/bin/env python3
"""Generates commands/command_table.c and docs/COMMANDS.md from scripts/commands.txt.
Run from the MiniOS folder:  python3 scripts/gen_commands.py
Edit scripts/commands.txt (one line per command), never the generated files."""
import re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATS = [("CAT_SHELL","shell",25),("CAT_FILE","file",35),("CAT_DIR","directory",20),
        ("CAT_PROCESS","process",30),("CAT_MEMORY","memory",15),("CAT_USER","user",20),
        ("CAT_SECURITY","security",15),("CAT_DISK","disk",25),("CAT_SYSTEM","system",25),
        ("CAT_TEXT","text",30),("CAT_NETWORK","network",20),("CAT_DEBUG","debug",20),
        ("CAT_OTHER","other",20)]
bounds, start = [], 1
for sym, name, n in CATS:
    bounds.append((start, start + n - 1, sym, name)); start += n

rows = []
for line in open(os.path.join(ROOT, "scripts/commands.txt"), encoding="utf-8"):
    line = line.rstrip("\n")
    if not line or line.startswith("#"): continue
    i, name, lvl, sub, desc = line.split("|", 4)
    rows.append((int(i), name, int(lvl), sub, desc))
ids = [r[0] for r in rows]
if ids != list(range(1, len(rows) + 1)): sys.exit("ids must run 1..N without gaps")
names = [r[1] for r in rows]
if len(set(names)) != len(names): sys.exit("duplicate command name")

def cat_of(i):
    for lo, hi, sym, name in bounds:
        if lo <= i <= hi: return sym, name
    sys.exit("id %d outside the category ranges" % i)

# which commands have a handler bound in commands/*_commands.c
implemented = set()
import glob
for sc in sorted(glob.glob(os.path.join(ROOT, "commands", "*_commands.c"))):
    implemented |= set(re.findall(r'\{\s*"(\w+)"\s*,\s*cmd_\w+\s*\}', open(sc).read()))

esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
out = ["/* GENERATED by scripts/gen_commands.py from scripts/commands.txt - do not edit by hand. */",
       '#include "include/command.h"', "",
       "command_t command_table[] = {"]
for i, name, lvl, sub, desc in rows:
    sym, _ = cat_of(i)
    out.append('    { %3d, "%s", "%s", "%s", %s, LEVEL_L%d, NULL },' % (i, name, esc(desc), sub, sym, lvl))
out += ["};", "",
        "const size_t command_table_len = sizeof(command_table) / sizeof(command_table[0]);",
        '_Static_assert(sizeof(command_table) / sizeof(command_table[0]) == COMMAND_EXPECTED,',
        '               "command table must contain exactly COMMAND_EXPECTED entries");', ""]
open(os.path.join(ROOT, "commands/command_table.c"), "w", encoding="utf-8").write("\n".join(out))

lv = {1: 0, 2: 0, 3: 0}
for r in rows: lv[r[2]] += 1
md = ["# MiniOS command list", "",
      "Generated from `scripts/commands.txt`. The live status is also shown by `help <category>` and `cmdinfo <name>` inside MiniOS.", "",
      "| Level | Meaning | Count |", "|---|---|---|",
      "| L1 | real, changes real kernel state | %d |" % lv[1],
      "| L2 | real, built on existing subsystems | %d |" % lv[2],
      "| L3 | SIMULATED, never touches real hardware | %d |" % lv[3],
      "| | **Total** | **%d** |" % len(rows),
      "", "Implemented now: **%d** of %d%s." % (len(implemented & set(names)), len(rows), " - every registered command has a handler" if len(implemented & set(names)) == len(rows) else " (the rest are registered stubs)"), ""]
for lo, hi, sym, name in bounds:
    md += ["## %s (%03d-%03d)" % (name.capitalize(), lo, hi), "", "| # | Command | Description | Level | Subsystem | Status |", "|---|---|---|---|---|---|"]
    for i, n, l, s, d in rows:
        if lo <= i <= hi:
            md.append("| %03d | `%s` | %s | L%d | %s | %s |" % (i, n, d, l, s, "implemented" if n in implemented else "planned"))
    md.append("")
open(os.path.join(ROOT, "docs/COMMANDS.md"), "w", encoding="utf-8").write("\n".join(md))
print("generated %d commands (L1=%d L2=%d L3=%d, %d implemented)" % (len(rows), lv[1], lv[2], lv[3], len(implemented & set(names))))
